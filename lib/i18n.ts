// Locales, UI strings and number formatting. Safe to import on server and client.

export const LOCALES = ["en", "id", "es", "ru"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "en";
export const LOCALE_PARAM = "lang";
export const LOCALE_HEADER = "x-locale";

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/** Best supported locale from an Accept-Language header, or null. */
export function matchAcceptLanguage(header: string | null): Locale | null {
  if (!header) return null;
  const ranked = header
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.find((p) => p.trim().startsWith("q="));
      return { tag: tag.toLowerCase(), q: q ? Number(q.trim().slice(2)) || 0 : 1 };
    })
    .sort((a, b) => b.q - a.q);
  for (const { tag } of ranked) {
    const primary = tag.split("-")[0];
    // "in" is the legacy code for Indonesian, still sent by some Android builds.
    const normalized = primary === "in" ? "id" : primary;
    if (isLocale(normalized)) return normalized;
  }
  return null;
}

/** Appends ?lang= to an internal path, keeping existing query params. */
export function withLocale(path: string, locale: Locale): string {
  const [pathname, query = ""] = path.split("?");
  const params = new URLSearchParams(query);
  params.set(LOCALE_PARAM, locale);
  return `${pathname}?${params.toString()}`;
}

const NUMBER = {
  en: { decimal: ".", thousand: "K", million: "M" },
  id: { decimal: ",", thousand: " rb", million: " jt" },
  es: { decimal: ",", thousand: " mil", million: " M" },
  ru: { decimal: ",", thousand: " тыс.", million: " млн" },
} as const;

/** Russian plural: plural(5, ["серия", "серии", "серий"]) → "серий". */
function plural(n: number, [one, few, many]: [string, string, string]): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
const episodesRu = (n: number) => `${n} ${plural(n, ["серия", "серии", "серий"])}`;

/**
 * Compact counter (12.4M / 12,4 jt / 12,4 M). Hand-rolled instead of
 * Intl compact notation so server and browser render the same string.
 */
export function formatCount(value: number, locale: Locale): string {
  const fmt = NUMBER[locale];
  const compact = (n: number, suffix: string) => {
    const rounded = n >= 100 ? Math.round(n).toString() : (Math.round(n * 10) / 10).toString();
    return rounded.replace(".", fmt.decimal) + suffix;
  };
  if (value >= 1_000_000) return compact(value / 1_000_000, fmt.million);
  if (value >= 1_000) return compact(value / 1_000, fmt.thousand);
  return value.toString();
}

